/** 统计（一次交付可用率 = ok / 总数；分档位也给一份，便于看"档位是否真的有用"） */
function outcomeStats(list) {
  const rows = Array.isArray(list) ? list : []
  const rate = (arr) => (arr.length === 0 ? null : Math.round((arr.filter((r) => r.verdict === 'ok').length / arr.length) * 1000) / 10)
  const byTier = {}
  for (const r of rows) { const k = r.tier || 'unknown'; byTier[k] = byTier[k] || []; byTier[k].push(r) }
  return {
    total: rows.length,
    ok: rows.filter((r) => r.verdict === 'ok').length,
    rework: rows.filter((r) => r.verdict === 'rework').length,
    okRatePercent: rate(rows),
    byTier: Object.keys(byTier).map((k) => ({ tier: k, total: byTier[k].length, okRatePercent: rate(byTier[k]) })),
  }
}
