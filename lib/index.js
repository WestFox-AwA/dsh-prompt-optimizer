/**
 * 转交语判定（首/尾专用）：只扫**首尾**——转交语与包装只出现在首尾；
 * 正文里出现"发给某某机器人"可能是任务本身（用户就是要写一份提示词），不能误伤。
 */
const XFER_HEAD_RES = [
  /(?:把|将)?\s*(?:下面|以下|底下)?\s*(?:这|那)(?:一)?(?:整)?(?:段|条|份|个)?[^\n]{0,14}?(?:发给|发送给|发送|转给|转发给|转发|交给)/,
  /(?:下面|以下|底下)\s*(?:这|那)?(?:一)?(?:整)?(?:段|条|份|个)?[^\n]{0,16}?(?:发给|发送|转给|转发|交给)/,
  /(?:发给|发送给|转给|转发给|交给)\s*(?:工作|会话|下游)?\s*(?:AI|助手|机器人|智能体|agent)/i,
  /^(?:以下|下面)(?:就)?是(?:我)?(?:为你|给你)?(?:优化|改写|重写|补全|整理)(?:后|好)?的/,
  /^你(?:可以|能)?(?:直接)?(?:把|将|复制|粘贴|发给|发送|使用)(?:这段|这条|这份|下面|以下|它)/,
  /^(?:这段|这条|这份)(?:优化后的?)?(?:提示词|指令|命令|内容|文字)?[^\n]{0,6}?(?:直接|可以|请)?\s*(?:发给|转给|转发)/,
]
const XFER_TAIL_RES = [
  // 必须是"对你（老板）问一句"的形状：主语"我"不可省——否则"如果需要调整参数…"这种合法指令会被误伤（实测踩过）
  /(?:需不需要|要不要|是否要|需要|要)我(?:再)?(?:帮你|替你|给你)?(?:调整|修改|改|补充|展开|细化)/,
  /(?:如果|如|若)(?:你)?(?:还)?(?:需要|想|要)(?:调整|修改|补充|更多|其他)[^\n]{0,16}(?:告诉|说一声|联系)我/,
  /(?:需要|要|想)(?:再)?(?:调整|修改|补充|展开|细化)[^\n]{0,10}(?:的话)?[，,]?\s*(?:请)?(?:告诉|说一声|联系)我/,
  /以上[，,]?\s*(?:请)?查收/,
  /希望(?:这|能|可以)?(?:对你)?(?:有)?(?:帮助|用)/,
  /^(?:我)?(?:已|已经)?(?:按|依照|根据)(?:你|您)(?:的)?(?:原话|要求|意思)[^\n]{0,28}(?:优化|改写|补全|整理)[^。！？\n]{0,4}$/,
]
/** 光杆分隔线（--- / *** / ___ / ===）：对"给工作 AI 的指令"没有意义，首尾一律剥掉。 */
const XFER_FENCE_RE = /^\s*(?:-{3,}|\*{3,}|_{3,}|={3,})\s*$/
const XFER_MIN_KEEP_CHARS = 20

/**
 * 闸门层：剥掉产出**首尾**的转交语与包装。硬约束：**绝不返回空**——
 * 剥完不足 XFER_MIN_KEEP_CHARS 就整段回退原文（任何失败路径都不给空结果）。
 * 返回 { text, triggered, action, before, after, head }，写进 run.addressee 供 /runs 复核。
 */
function enforceAddressee(raw) {
  const src = typeof raw === 'string' ? raw : String(raw === undefined || raw === null ? '' : raw)
  const plain = (action) => ({ text: src, triggered: false, action, before: src.length, after: src.length, head: '' })
  if (!src.trim()) return plain('empty')
  try {
    const lines = src.split('\n')
    const drop = new Set()
    const seen = []
    let hitHead = false
    let hitTail = false
    // ① 首部：跳空行后连续剥（命中行 + 紧跟的空行/分隔线），最多 3 行
    let i = 0
    while (i < lines.length && lines[i].trim() === '') i++
    for (let n = 0; n < 3 && i < lines.length; n++) {
      const t = lines[i].trim()
      if (t === '') break
      const hit = XFER_HEAD_RES.some((re) => re.test(t))
        || (n > 0 && /(?:发给|发送|转给|转发)/.test(t) && /(?:AI|助手|机器人|提示词|指令)/.test(t))
      if (!hit) break
      hitHead = true
      seen.push(t.slice(0, 60))
      drop.add(i); i++
      while (i < lines.length && (lines[i].trim() === '' || XFER_FENCE_RE.test(lines[i]))) { drop.add(i); i++ }
    }
    // ② 首部残留的包装分隔线
    let a = 0
    while (a < lines.length && lines[a].trim() === '') a++
    while (a < lines.length && XFER_FENCE_RE.test(lines[a])) { drop.add(a); a++ }
    // ③ 尾部：分隔线无条件剥；转交语连续剥，最多 3 行
    let k = lines.length - 1
    while (k >= 0 && lines[k].trim() === '') k--
    while (k >= 0 && XFER_FENCE_RE.test(lines[k])) { drop.add(k); k-- }
    for (let n = 0; n < 3 && k >= 0; n++) {
      const t = lines[k].trim()
      if (t === '' || !XFER_TAIL_RES.some((re) => re.test(t))) break
      hitTail = true
      seen.push(t.slice(0, 60))
      drop.add(k); k--
      while (k >= 0 && (lines[k].trim() === '' || XFER_FENCE_RE.test(lines[k]))) { drop.add(k); k-- }
    }
    if (drop.size === 0) return plain('no-hit')
    const kept = lines.filter((_, idx) => !drop.has(idx)).join('\n').trim()
    if (kept.length < XFER_MIN_KEEP_CHARS) {
      // 判定命中但剥了会伤正文 → 保留原文，只记账（宁可漏一次，也不丢内容）
      return { text: src, triggered: true, action: 'hit-but-keep-original', before: src.length, after: src.length, head: seen.join(' / ').slice(0, 120) }
    }
    const acts = []
    if (hitHead) acts.push('head')
    if (hitTail) acts.push('tail')
    if (acts.length === 0) acts.push('fence')
    return { text: kept, triggered: true, action: 'strip-' + acts.join('+'), before: src.length, after: kept.length, head: seen.join(' / ').slice(0, 120) }
  } catch (error) {
    return { text: src, triggered: false, action: 'error-passthrough:' + String(error).slice(0, 60), before: src.length, after: src.length, head: '' }
  }
}

