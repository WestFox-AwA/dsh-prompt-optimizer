function shortReason(value, cap) {
  const s = String(value === undefined || value === null ? '' : value).replace(/\s+/g, ' ').trim()
  return s.length > (cap || 90) ? s.slice(0, cap || 90) + '…' : s
}

/** 本会话的沙箱策略：读服务；读不到就标 unknown（**不猜档位**，猜档位正是病根）。 */
function capabilityPolicyOf(ctx, session) {
  const fallback = { mode: 'unknown', workspaceRoot: process.cwd() }
  try {
    const sp = ctx.get('sandboxPolicy')
    if (sp && typeof sp.resolve === 'function') {
      const p = sp.resolve({ session })
      if (p && p.mode) return { mode: String(p.mode), workspaceRoot: p.workspaceRoot || process.cwd() }
    }
  } catch { /* 服务缺失即 unknown */ }
  return fallback
}

/** 本会话的审批策略：never = 没有任何操作需要审批（不是"没有权限"）。 */
function capabilityApprovalOf(ctx, session) {
  try {
    const ap = ctx.get('approval')
    if (ap && typeof ap.effectivePolicy === 'function') return String(ap.effectivePolicy(session) || 'unknown')
    if (ap && typeof ap.overrideOf === 'function') {
      const over = ap.overrideOf(session)
      if (over) return String(over)
      if (ap.config && ap.config.policy) return String(ap.config.policy)
    }
  } catch { /* ignore */ }
  return 'unknown'
}

/** 走**该会话自己的沙箱策略**跑一条命令（与工作 AI 的 pwsh 同一条路径，所以实测值可信）。 */
function probeShell(ctx, policy, command, timeoutMs) {
  return new Promise((resolve) => {
    let shell = null
    try { shell = ctx.get('shell') } catch { shell = null }
    if (!shell || typeof shell.resolve !== 'function' || typeof shell.run !== 'function') {
      resolve({ ok: false, why: 'shell 服务不可用' })
      return
    }
    let spec = null
    try {
      spec = shell.resolve({
        command,
        workdir: policy.workspaceRoot,
        timeoutMs,
        sandboxPolicy: { mode: policy.mode, workspaceRoot: policy.workspaceRoot },
      })
    } catch (error) {
      resolve({ ok: false, why: 'resolve: ' + shortReason(error && error.message, 70) })
      return
    }
    Promise.resolve()
      .then(() => shell.run(spec))
      .then((r) => {
        const denied = !!(r && r.sandbox && r.sandbox.denied)
        resolve({
          ok: !!(r && r.exitCode === 0) && !denied,
          exitCode: r ? r.exitCode : null,
          out: shortReason(r && r.stdout && r.stdout.text, 120),
          err: shortReason(r && r.stderr && r.stderr.text, 120),
          denied,
          timedOut: !!(r && r.timedOut),
        })
      })
      .catch((error) => resolve({ ok: false, why: shortReason(error && error.message, 90) }))
  })
}

