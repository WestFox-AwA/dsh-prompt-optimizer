/**
 * 视觉截图探测脚本：**把踩过的坑写进脚本本身**——
 *   私有 `--user-data-dir`（否则参数被已开着的浏览器实例吞掉，返回一句中文就结束）、
 *   软件渲染（无 GPU 时 WebGL 画面全黑）、
 *   以及**轮询等落盘**（启动器立刻返回，图 0.3–1s 后才出现；立刻查等于必判失败）。
 */
function renderProbeScript(exe, htmlPath, pngPath, profileDir) {
  if (process.platform === 'win32') {
    const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
    return [
      `$exe = ${q(exe)}`,
      `$png = ${q(pngPath)}`,
      `Remove-Item -LiteralPath $png -Force -ErrorAction SilentlyContinue`,
      `$flags = @('--headless=new','--disable-gpu','--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader','--no-first-run','--no-default-browser-check','--window-size=480,320','--virtual-time-budget=3000',${q('--user-data-dir=' + profileDir)},${q('--screenshot=' + pngPath)},${q('file:///' + String(htmlPath).replace(/\\/g, '/'))})`,
      `$out = & $exe @flags 2>&1 | Out-String`,
      `for ($i = 0; $i -lt 24; $i++) { Start-Sleep -Milliseconds 250; if (Test-Path -LiteralPath $png) { break } }`,
      `if (Test-Path -LiteralPath $png) { 'PO_SHOT_OK ' + (Get-Item -LiteralPath $png).Length } else { 'PO_SHOT_NONE ' + ($out -replace '\\s+',' ') }`,
    ].join('\n')
  }
  const q = (s) => "'" + String(s).replace(/'/g, "'\\''") + "'"
  return [
    `png=${q(pngPath)}`,
    `rm -f "$png"`,
    `${q(exe)} --headless=new --disable-gpu --no-sandbox --enable-unsafe-swiftshader --use-angle=swiftshader --no-first-run --no-default-browser-check ${q('--user-data-dir=' + profileDir)} --window-size=480,320 --virtual-time-budget=3000 ${q('--screenshot=' + pngPath)} ${q('file://' + htmlPath)} >/dev/null 2>&1 || true`,
    `for i in $(seq 1 24); do sleep 0.25; [ -f "$png" ] && break; done`,
    `if [ -f "$png" ]; then echo PO_SHOT_OK $(wc -c < "$png"); else echo PO_SHOT_NONE; fi`,
  ].join('\n')
}

/** 三个通道实测（并行；每个都有自己的超时，绝不拖住装配）。 */
async function probeChannels(ctx, policy) {
  const procCmd = process.platform === 'win32' ? 'cmd /c echo PO_PROC_OK' : 'echo PO_PROC_OK'
  const procPromise = probeShell(ctx, policy, procCmd, 15000).then((r) => {
    const err = String(r.err || '')
    // read-only 档实测：命令能跑，但 PowerShell 处于受限语言模式（.NET/Add-Type/COM 全废）。
    // 这是"部分可用"，必须如实写出来——既不夸大成"没权限"，也不假装没这回事。
    const constrained = /core types are supported|ConstrainedLanguage/i.test(err) || /core types are supported|ConstrainedLanguage/i.test(String(r.out || ''))
    return {
      ok: r.ok && String(r.out || '').includes('PO_PROC_OK'),
      constrained,
      why: r.why || '',
      err: r.err || r.out || '',
      denied: !!r.denied,
      exitCode: r.exitCode,
    }
  })

  const exe = capabilityBrowser()
  const html = exe ? capabilityProbeHtml() : null
  let renderPromise
  if (!exe || !html) {
    renderPromise = Promise.resolve({ ok: false, why: exe ? '探测页面写入失败' : '本机没有可用的浏览器可执行文件', skipped: true })
  } else {
    const tag = String(Date.now()) + '-' + Math.random().toString(36).slice(2, 8)
    const png = join(tmpdir(), 'po-capability', 'shot-' + tag + '.png')
    const profile = join(tmpdir(), 'po-capability', 'profile')
    const started = Date.now()
    renderPromise = probeShell(ctx, policy, renderProbeScript(exe, html, png, profile), 45000).then((r) => {
      const text = String(r.out || '') + ' ' + String(r.err || '')
      const m = /PO_SHOT_OK (\d+)/.exec(text)
      const bytes = m ? Number(m[1]) : 0
      const ok = !!m && bytes > 0
      let why = ''
      if (!ok) {
        if (r.denied) why = '被沙箱拒绝'
        else if (r.why) why = r.why
        else if (/Access is denied|拒绝访问/.test(text)) why = shortReason(text, 90)
        else if (r.timedOut) why = '超时'
        else why = shortReason(text.replace('PO_SHOT_NONE', '').trim() || ('exit ' + r.exitCode), 90)
      }
      try { if (existsSync(png)) rmSyncSafe(png) } catch { /* best effort */ }
      return { ok, bytes, ms: Date.now() - started, browser: exe.split(/[\\/]/).pop(), why, skipped: false }
    })
  }
  const [proc, render] = await Promise.all([procPromise, renderPromise])
  return { proc, render, at: Date.now(), mode: policy.mode }
}

function rmSyncSafe(p) {
  try { unlinkSync(p) } catch { /* best effort */ }
}

/** 取（或触发）当前档位对应的通道实测结果；探测进行中先给旧值，**同步返回**。 */
function capabilityStateFor(ctx, policy) {
  const now = Date.now()
  const key = String(policy.mode)
  const entry = capabilityCache.get(key)
  const fresh = !!(entry && entry.value && entry.at && now - entry.at < CAPABILITY_TTL_MS)
  if (!fresh && !(entry && entry.pending)) {
    const started = probeChannels(ctx, policy)
      .then((value) => {
        capabilityCache.set(key, { at: Date.now(), value, pending: false })
        capabilityNotes.push({ t: Date.now(), event: 'probe', key, ok: { proc: value.proc.ok, render: value.render.ok } })
      })
      .catch((error) => {
        capabilityCache.set(key, { at: Date.now(), value: { error: shortReason(error && error.message, 120) }, pending: false })
      })
    capabilityCache.set(key, { at: (entry && entry.at) || 0, value: (entry && entry.value) || null, pending: true, promise: started })
  }
  const cur = capabilityCache.get(key)
  return { key, value: (cur && cur.value) || null, probing: !!(cur && cur.pending) }
}

/** 外部工具服务器（MCP）：从工具注册表枚举，权威、零探测；覆盖"去别的开发软件里工作"这类环境。 */
let mcpSnapshot = { at: 0, servers: null }
function mcpServersOf(ctx, assembly) {
  const now = Date.now()
  if (mcpSnapshot.servers && now - mcpSnapshot.at < 60 * 1000) return mcpSnapshot.servers
  try {
    const tools = ctx.get('tools')
    if (tools && typeof tools.schemas === 'function') {
      let list = null
      try { list = tools.schemas(assembly && assembly.scope) } catch { list = null }
      if (!list) list = tools.schemas()
      const servers = new Set()
      for (const s of list || []) {
        const m = /^mcp__(.+?)__/.exec(String(s && s.name))
        if (m) servers.add(m[1])
      }
      mcpSnapshot = { at: now, servers: [...servers] }
      return mcpSnapshot.servers
    }
  } catch { /* ignore */ }
  return mcpSnapshot.servers
}

function reasonSuffix(result) {
  if (!result) return ''
  let why = result.why || ''
  if (!why && result.denied) why = '被沙箱拒绝'
  if (!why && result.timedOut) why = '超时'
  if (!why && result.err) why = result.err
  if (!why && result.exitCode !== undefined && result.exitCode !== null) why = 'exit ' + result.exitCode
  why = shortReason(why, 90)
  return why ? '（' + why + '）' : ''
}

function channelTextOf(state) {
  if (!state.value) return state.probing ? '子进程（首次探测中）· 视觉截图（首次探测中）' : '（通道未探测）'
  const parts = []
  const proc = state.value.proc || {}
  parts.push('子进程 ' + (proc.ok ? '✓' + (proc.constrained ? '（受限语言模式：.NET/Add-Type/COM 不可用）' : '') : '✗' + reasonSuffix(proc)))
  const render = state.value.render || {}
  if (render.ok) {
    parts.push('视觉截图 ✓（' + (render.browser || '无头浏览器') + ' ' + (Math.round((render.ms || 0) / 100) / 10) + 's 出图 ' + (render.bytes || 0) + 'B）')
  } else {
    parts.push('视觉截图 ✗' + reasonSuffix(render))
  }
  if (state.probing) parts.push('（本档位正在重测）')
  return parts.join(' · ')
}

/**
 * 系统提示里的一小段**实测事实**（每个会话每次装配都算，但不做任何阻塞 IO）：
 * 权限档 + 审批 + 通道实测 + 外部工具服务器，外加一条通用判断规则。
 */
function renderCapabilityFacts(ctx, assembly, policyOverride) {
  try {
    const session = assembly && assembly.agent && assembly.agent.session
    if (!session) return ''
    const policy = policyOverride || capabilityPolicyOf(ctx, session)
    const approval = policyOverride
      ? (policyOverride.mode === 'danger-full-access' ? 'never' : 'ask')
      : capabilityApprovalOf(ctx, session)
    const state = capabilityStateFor(ctx, policy)
    const servers = mcpServersOf(ctx, assembly)
    const out = []
    const modeText = policy.mode === 'danger-full-access'
      ? 'danger-full-access（文件与进程都不设限）'
      : String(policy.mode)
    const apprText = approval === 'never'
      ? '不需要任何审批'
      : (approval === 'ask' ? 'ask（需要时会申请）' : String(approval))
    const extText = servers === null
      ? '（未能枚举）'
      : (servers.length ? servers.join('、') + ' ✓' : '无（本会话没有外部工具服务器，只能用本机工具）')
    out.push('【本会话实测能力】权限档 ' + modeText + '｜审批 ' + apprText + '。通道：' + channelTextOf(state) + ' · 外部工具服务器：' + extText + '。')
    if (policy.mode === 'danger-full-access') {
      out.push('（工具说明里关于受限档的警告——命名管道 EPERM、ConstrainedLanguage、.NET/Add-Type、提权审批——在本会话**不适用**；只有真的收到 denied 才算被拒。）')
    }
    out.push('【失败不是结论】"被拒绝/做不到"只能由**当场复测**确认：权限档或环境变过，之前失败得出的结论一律作废，重测再下判断。能自动验证的（截图、编译、断言、跑一遍）不要交给用户；只有主观手感或真机体验才交回，并写清你验了什么、没验什么、为什么。')
    return out.join('\n')
  } catch { return '' }
}

