/**
 * 有上限的 Map（P1 代码卫生）：liveRuns / optSessions 长期运行会无界增长。
 * 淘汰策略：超过上限时按插入顺序删最旧的；**status === 'running' 的条目永不淘汰**
 *（否则会掐断正在推送的 SSE 流）。
 */
class CappedMap extends Map {
  constructor(max) { super(); this.max = max }
  set(key, value) {
    super.set(key, value)
    if (this.size > this.max) {
      for (const [k, v] of this) {
        if (this.size <= this.max) break
        if (v && v.status === 'running') continue
        this.delete(k)
      }
    }
    return this
  }
}
const optSessions = new CappedMap(64)
