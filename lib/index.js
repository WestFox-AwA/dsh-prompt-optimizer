async function streamWithTools(llm, selection, system, messages, tools, temperature, budgetMs, externalSignal, onDelta) {
  const t0 = Date.now()
  let reasoning = ''
  let text = ''
  let usage = null
  let firstDeltaMs = null
  let error = null
  let finish = null
  const calls = []
  const ac = new AbortController()
  // 预算分两层（**唯一来源**见 OUTPUT_BUDGET_MS）：
  //   ① 硬上限：绝对兜底——但**不再**用"总时长"当实际限制器；
  //   ② 停顿看门狗：只有**长时间没有任何增量**才收手。
  // 为什么改：按总时长砍，砍掉的是"还在稳定产出"的健康请求，用户拿到的是**半截命令**
  //（同一批 10 题里实测 1 题；chat/ptc 两形态各 1 题）。停止产出才是真的卡住。
  const hardTimer = setTimeout(() => ac.abort(), budgetMs || LOOP_BUDGET_MS)
  const STALL_MS = Number(process.env.DSH_PO_STALL_MS || 45000)
  let stallTimer = setTimeout(() => ac.abort(), STALL_MS)
  const bumpStall = () => { clearTimeout(stallTimer); stallTimer = setTimeout(() => ac.abort(), STALL_MS) }
  if (externalSignal) { if (externalSignal.aborted) ac.abort(); else externalSignal.addEventListener('abort', () => ac.abort(), { once: true }) }
  optimizerCallDepth += 1
  try {
    const stream = llm.stream({
      provider: selection.provider,
      model: selection.model,
      system,
      temperature,
      messages,
      signal: ac.signal,
      // 思考强度：由调用方挂在 selection 上（resolveEffortForCall 已确认该模型声明了它）；
      // 未挂 = 不发该字段 = 保持适配器默认（历史行为）。
      ...(selection.reasoningEffort ? { reasoningEffort: selection.reasoningEffort } : {}),
      ...(tools ? { tools } : {}),
    })
    for await (const chunk of stream) {
      if (chunk.type === 'reasoning-delta') {
        if (firstDeltaMs === null) firstDeltaMs = Date.now() - t0
        reasoning += chunk.text
        bumpStall()
        if (typeof onDelta === 'function') onDelta('reasoning-delta', chunk.text)
      } else if (chunk.type === 'text-delta') {
        if (firstDeltaMs === null) firstDeltaMs = Date.now() - t0
        text += chunk.text
        bumpStall()
        if (typeof onDelta === 'function') onDelta('text-delta', chunk.text)
      } else if (chunk.type === 'tool-call-delta') {
        let call = calls.find((c) => c.id === chunk.id)
        if (!call) { call = { id: chunk.id, name: chunk.name || '', arguments: '' }; calls.push(call) }
        if (chunk.name) call.name = chunk.name
        call.arguments += chunk.argumentsDelta || ''
      } else if (chunk.type === 'block-end' && chunk.block && chunk.block.type === 'tool-call') {
        const block = chunk.block
        const existing = calls.find((c) => c.id === block.id)
        if (existing) { existing.name = block.name || existing.name; existing.arguments = block.arguments || existing.arguments }
        else calls.push({ id: block.id, name: block.name, arguments: block.arguments })
      } else if (chunk.type === 'usage') {
        // usage 随流到达（不同 provider 可能多次/最后一次给全量）：立刻转发给前端做 token 计数
        usage = chunk.usage
        if (typeof onDelta === 'function') onDelta('usage', JSON.stringify(chunk.usage || {}))
      }
      else if (chunk.type === 'finish') {
        finish = chunk.reason
        if (chunk.reason && (chunk.reason.kind === 'error' || chunk.reason.kind === 'aborted')) {
          error = 'llm-' + chunk.reason.kind + ': ' + JSON.stringify(chunk.reason.failure || {})
        }
      }
    }
  } catch (error_) {
    error = String(error_)
  } finally {
    clearTimeout(hardTimer)
    clearTimeout(stallTimer)
    optimizerCallDepth -= 1
  }
  return { ms: Date.now() - t0, firstDeltaMs, reasoning, text, usage, error, finish, calls }
}

/**
 * 依据分类（SPEC W2/W3）：同一次工具调用，"读到内容"与"只列过目录"是**两种不同的依据**，
 * 前者可以支撑"文件里有什么"，后者只能支撑"存在哪些文件"。分错了就会出假事实。
 */
function parseToolEvidence(tool, args, text) {
  const out = { tool, readPath: null, listed: [], hits: [] }
  const s = String(text || '')
  if (tool === 'read') {
    const m = /^文件\s+(.+?)（共\s*(\d+)\s*行/.exec(s)
    if (m) out.readPath = m[1]
  } else if (tool === 'glob') {
    const body = s.indexOf('：\n') >= 0 ? s.slice(s.indexOf('：\n') + 2) : ''
    for (const line of body.split('\n')) { const p = line.trim(); if (p) out.listed.push(p) }
  } else if (tool === 'grep') {
    for (const line of s.split('\n')) { const m = /^(.+?):(\d+):/.exec(line.trim()); if (m) out.hits.push(m[1] + ':' + m[2]) }
  }
  return out
}
/**
 * 依据索引（SPEC W2/W3 · 证据层的渲染器）：把本次工具循环**实际读到了什么**渲染成一份可引用的清单。
 *
 * 它回答的是"你能引用什么、该怎么写出处"，而不是"你该注意什么"：
 *   · read  → 给出可引用的 `路径`（以及行数），命令里的事实要写成 `路径:位置`；
 *   · grep  → 给出命中的 `路径:行号`（这才是可核对的定位）；
 *   · glob  → 只算"有哪些文件"，**不得**据此推断文件里写了什么；
 *   · 一次内容都没读到 → 不得写"已核实的事实"，直接按用户原话给要求。
 */
function evidenceIndex(trace) {
  const rows = (Array.isArray(trace) ? trace : []).filter((t) => t && t.ok)
  const paths = []
  const listed = []
  const hits = []
  for (const t of rows) {
    const ev = t.evidence || parseToolEvidence(t.tool, t.args || {}, t.resultPreview || '')
    if (ev.readPath) paths.push(ev.readPath)
    for (const p of ev.listed || []) listed.push(p)
    for (const h of ev.hits || []) hits.push(h)
  }
  return {
    reads: rows.filter((t) => t.tool === 'read').length,
    paths: [...new Set(paths)],
    listed: [...new Set(listed)],
    hits: [...new Set(hits)],
  }
}
function renderEvidenceLedger(trace) {
  const rows = Array.isArray(trace) ? trace : []
  const idx = evidenceIndex(trace)
  const out = ['【本次依据索引】下面是你**实际读到**的东西——它是你唯一可以当作"事实"引用的来源：']
  if (rows.length === 0) out.push('- （本次没有执行任何查证动作）')
  for (const t of rows.slice(-12)) {
    let args = ''
    try { args = JSON.stringify(t.args || {}).slice(0, 72) } catch { args = '' }
    out.push('- ' + String(t.tool) + '(' + args + ') → ' + (t.ok ? String(t.resultLines) + ' 行' : '失败'))
  }
  if (idx.paths.length > 0) out.push('读到内容的文件（可引用内容与位置）：' + idx.paths.slice(0, 8).join('、'))
  if (idx.hits.length > 0) out.push('命中位置（可引用 `路径:行号`）：' + idx.hits.slice(0, 8).join('、'))
  if (idx.listed.length > 0) out.push('只列过目录、**没读过内容**的文件（只能陈述"存在"，不得描述里面写了什么）：' + idx.listed.slice(0, 12).join('、'))
  out.push('规则：')
  out.push('- 只允许引用上面出现过的路径 / 符号，并且**把出处写进命令**（写成 `路径:行号` 或 `路径 → 函数名`）——下游据此核对，不必猜。')
  out.push('- **只列过目录不等于知道内容**：上一条"只列过目录"里的文件，只能写"存在 / 有哪些"，不得推断文件里写了什么。')
  if (idx.reads === 0) out.push('- ⚠️ 你这次**一次文件内容都没读到**：不得写"已核实的事实/项目现状"这类段落，直接按用户原话给出要求。')
  return out.join('\n')
}

/** 极端档的只读工具循环：模型自己决定读什么/搜什么，直到给出结论或撞上限。 */
async function runToolLoop(ctx, opts) {
  const llm = ctx.get('llm')
  // 外部可传 selection（携带 resolveEffortForCall 判定过的思考强度），否则回落到会话默认模型
  let selection = opts.selection && opts.selection.provider ? opts.selection : null
  if (!selection) {
    try { const def = ctx.get('agentDefaultModel'); if (def) selection = def.currentSelection() } catch { /* fall through */ }
  }
  if (!selection || !selection.provider) selection = lastRoute
  const root = opts.root
  const maxRounds = opts.maxRounds || 3
  const trace = []
  const system = opts.system || (TIER_SPECS.extreme.system + '\n\n【只读查证】你可以调用 read/glob/grep 三个只读工具查证项目实际情况（限定在项目根内、不写盘、不执行命令）。需要项目事实时必须先查证再下结论；不得编造未查到的内容。')
  const messages = userMessageFor(opts.userText)
  // 顶层清单**预注入**：省掉"先 glob 一遍看看有什么"的那一轮（实测：模型把整轮预算花在 glob 上，
  // 三次运行都只"列到"约定文件、一次都没 read）。清单只声明**存在**，不等于知道内容——这条写清楚。
  if (root) {
    try {
      const top = walkFiles(root, 60).map((abs) => relative(root, abs).split('\\').join('/'))
      const roots = top.filter((p) => p.indexOf('/') < 0).slice(0, 40)
      if (roots.length) messages.push(...userMessageFor('【工具根目录顶层清单（只表示存在，不代表知道内容）】\n' + roots.join('\n') + '\n\n要引用文件里的东西，仍然必须用 read 真正读它。'))
    } catch { /* best effort */ }
  }
  let rounds = 0
  let converged = false
  let capped = false
  let output = ''
  let reasoningAll = ''
  let error = null
  let lastFinish = null
  let debug = null
  const deadline = Date.now() + (opts.budgetMs || LOOP_BUDGET_MS)
  // 产出流式（0.4.6-beta.6）：工具循环每一轮的正文**实时**转出去，换轮时清一次上一轮的脚手架。
  // 病根：此前循环只把最终一轮的正文攒到结束才 publishRun（实测 text-delta 只有 1 批、出现在第 36 秒），
  // 于是"思考"栏在流、"产出"栏静止——用户实测反馈正是这个。
  let roundTextChars = 0
  const bridge = (type, text) => {
    if (type === 'text-delta') roundTextChars += String(text || '').length
    if (typeof opts.onDelta === 'function') opts.onDelta(type, text)
  }
  for (let round = 1; round <= maxRounds + 1; round += 1) {
    const useTools = round <= maxRounds && Date.now() < deadline
    // 换轮：上一轮的文字是脚手架（"我先读一下项目结构…"），清掉让"产出"栏只显示当前这一轮
    if (round > 1) { roundTextChars = 0; if (typeof opts.onDelta === 'function') opts.onDelta('text-reset', '') }
    if (round === 1) {
      // 请求形状留痕：定位 400（messages[0].content invalid type: sequence）到底来自哪条消息
      debug = {
        systemChars: String(system || '').length,
        toolsCount: useTools ? LOOP_TOOLS.length : 0,
        // 最后几个未记录的变量：模型路由、预算/信号、以及用户消息开头（用于排除文本层面的干扰）
        selection: selection && selection.provider
          ? { provider: selection.provider, model: selection.model, reasoningEffort: selection.reasoningEffort === undefined ? null : selection.reasoningEffort }
          : null,
        budgetMs: Math.max(0, Math.round(deadline - Date.now())),
        hasSignal: Boolean(opts.externalSignal),
        userHead: String(opts.userText || '').slice(0, 160),
        messages: messages.map((m) => ({
          role: m && m.role,
          content: m && typeof m.content === 'string'
            ? 'string'
            : (m && Array.isArray(m.content) ? 'blocks(' + m.content.map((b) => (b && b.type) || '?').join(',') + ')' : typeof (m && m.content)),
        })),
      }
    }
    // 思考/用量/正文走**与不派工具时同一条透传通道**（bridge 会记下本轮是否已有正文，用于最终定稿去重）。
    // 此前漏传第 9 个参数 onDelta：工具循环把 reasoning 只累加进 reasoningAll、只回传一个计数，
    // 于是高级/极端档（都要走工具循环）的"思考"栏永远是空的，而基础档正常——断点就在这一行。
    const res = await streamWithTools(llm, selection, system, messages, useTools ? LOOP_TOOLS : undefined, TIER_SPECS.extreme.temperature, deadline - Date.now(), opts.externalSignal, bridge)
    rounds = round
    reasoningAll += res.reasoning
    output = res.text
    lastFinish = res.finish || lastFinish
    if (res.error) { error = res.error; break }
    if (!useTools && round > maxRounds) { converged = Boolean(res.text && res.text.trim()); break }
    if (!res.calls || res.calls.length === 0) break
    messages.push(...assistantToolCallMessage(res.calls, selection))
    const outputs = []
    for (const call of res.calls) {
      let args = {}
      try { args = JSON.parse(call.arguments || '{}') } catch { args = {} }
      const t0 = Date.now()
      let text = ''
      let ok = true
      try { text = executeReadOnlyTool(root, call.name, args) } catch (e) { ok = false; text = 'ERROR: ' + String(e) }
      const rec = { round, tool: call.name, args, ok, ms: Date.now() - t0, resultLines: String(text).split('\n').length, resultPreview: String(text).slice(0, 240), evidence: parseToolEvidence(call.name, args, text) }
      trace.push(rec)
      // **实时**把这次查证动作发出去：工具期的"产出"栏本来就没有正文（模型在调工具、还没写答案），
      // 没有这条信号，整轮会看着像卡住（实测前 26 秒只有思考在动）。
      if (typeof opts.onDelta === 'function') opts.onDelta('tool-trace', JSON.stringify({ round: rec.round, tool: rec.tool, args: rec.args, ok: rec.ok, ms: rec.ms, resultLines: rec.resultLines }))
      outputs.push({ ok, text: String(text) })
    }
    messages.push(...toolResultMessages(res.calls, outputs))
    // ── 证据层（结构性输入）：把"本次实际读到了什么"作为**唯一可引用的来源**交给模型 ──
    // 病根：产出里的"项目现状（已核实）"此前可以来自**只列过目录**、甚至来自**读错的目录**——
    // 下游拿到假事实就不再去看真实项目。账本让"能引用什么"变成一条可核对的事实，而不是一句提醒。
    const ledger = renderEvidenceLedger(trace)
    messages.push(...userMessageFor(ledger))
    if (debug) {
      const idx = evidenceIndex(trace)
      debug.evidenceChars = ledger.length
      debug.evidenceReads = trace.filter((t) => t.ok && t.tool === 'read').length
      // ⚠️ 这三份清单是**出处审计的输入**，截断会造成误判（实测：只留 12 条时，glob 的 html 结果被切掉，
      // 审计把"确实列过的文件"判成"凭空出现"）。上限放到工具自身的返回上限量级即可。
      debug.evidencePaths = idx.paths.slice(0, 20)
      debug.evidenceHits = idx.hits.slice(0, 20)
      debug.evidenceListed = idx.listed.slice(0, 60)
    }
    if (round === maxRounds) {
      capped = true
      messages.push(...userMessageFor('【系统】已达本次查证轮次上限，请立即用已获得的证据给出阶段性结论，不要再请求工具。'))
    }
  }
  // 只读范围负例：越界路径必须被拒
  let scopeProbe = null
  try { scopeProbe = { result: executeReadOnlyTool(root, 'read', { path: '../../../../etc/hosts' }) } } catch (e) { scopeProbe = { error: String(e) } }
  return { root, maxRounds, rounds, capped, converged, error, debug, finish: lastFinish, trace, output, reasoning: reasoningAll, reasoningChars: reasoningAll.length, streamedText: roundTextChars > 0, scopeProbe, selection, llmOk: Boolean(llm), assistantMessages: messages.filter((m) => m.role === 'assistant').length }
}

/** 小类 2.3 核验器：正常查证（行级可核对）+ 超限收敛 + 越界拒绝。 */
