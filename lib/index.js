/* ══════════════ 实时流（小类 3.2：思考/产出分通道，SSE 推给浮层） ══════════════ */
const liveRuns = new CappedMap(64)
let liveSeq = 0

function publishRun(run, event) {
  if (event.type === 'reasoning-delta') {
    if (run.firstDeltaMs === null) run.firstDeltaMs = Date.now() - run.startedAt
    run.reasoning += event.text
  } else if (event.type === 'text-delta') {
    if (run.firstDeltaMs === null) run.firstDeltaMs = Date.now() - run.startedAt
    run.text += event.text
  } else if (event.type === 'text-reset') {
    // 工具循环换轮：清掉已累积的正文（与前端一致）。这样 run.text 始终等于"当前这一轮"，
    // 最终 done.text（与收件人闸门）拿到的就是干净答案，而不是脚手架 + 答案的拼接。
    run.text = ''
  } else if (event.type === 'tool-trace') {
    // 工具循环**实时**查证动作：让「查证动作」栏在工具期就动起来
    //（此前该栏喂的是 /trace 自检数据，实跑时全程不动）
    let rec = null
    try { rec = JSON.parse(event.text || '{}') } catch { rec = null }
    if (rec) run.traceLive = (run.traceLive || []).concat([rec]).slice(-12)
  } else if (event.type === 'usage') {
    // 逐次覆盖（provider 常在末尾给全量）；同时累加累计值供展示
    const raw = event.usage !== undefined ? event.usage : event.text
    let parsed = null
    try { parsed = typeof raw === 'string' ? JSON.parse(raw) : raw } catch { parsed = null }
    if (parsed && typeof parsed === 'object') {
      run.usage = parsed
      run.usageAt = Date.now()
    }
  } else if (event.type === 'aborted') {
    run.status = 'aborted'
  } else if (event.type === 'error') {
    run.status = 'error'
    run.error = event.message
  } else if (event.type === 'done') {
    run.status = 'done'
  }
  const line = 'data: ' + JSON.stringify(event) + '\n\n'
  for (const sub of [...run.subs]) {
    try { sub.write(line) } catch { run.subs.delete(sub) }
  }
}

function closeRunSubs(run) {
  for (const sub of [...run.subs]) {
    try { sub.end() } catch { /* noop */ }
  }
  run.subs.clear()
}

async function executeLiveRun(ctx, run) {
  const spec = TIER_SPECS[run.tier] || TIER_SPECS.basic
  const llm = ctx.get('llm')
  let selection = null
  try { const def = ctx.get('agentDefaultModel'); if (def) selection = def.currentSelection() } catch { /* fall through */ }
  if (!run.provider || !run.model) { const st = loadPluginState(); if (st.model) { run.provider = st.model.provider; run.model = st.model.model } }
  if (run.provider && run.model) selection = { provider: run.provider, model: run.model }
  if (run.forceError) selection = { provider: 'dpo-invalid-provider', model: 'dpo-invalid-model' }
  if (!selection || !selection.provider) selection = lastRoute
  if (selection) { run.provider = selection.provider; run.model = selection.model || null }
  // 思考强度：把配置值**真正带进调用**（模型未声明该档位时不发——避免残留值让正式优化失败）
  const effortPlan = await resolveEffortForCall(llm, selection)
  run.effort = effortPlan.configured
  run.effortSent = effortPlan.sent
  run.effortNote = effortPlan.reason
  const selForRun = effortPlan.sent ? Object.assign({}, selection, { reasoningEffort: effortPlan.sent }) : selection
  try {
    const digest = collectDialogueDigest(ctx, run.sessionId, run.turns, run.historyMode)
    const historyBlock = renderHistoryBlock(digest)
    if (digest) {
      run.history = { mode: digest.mode || run.historyMode || 'turns', source: digest.source || null, rawEvents: digest.rawEvents === undefined ? null : digest.rawEvents, rawUsers: digest.rawUsers === undefined ? null : digest.rawUsers, dropped: digest.dropped === undefined ? null : digest.dropped, turns: digest.turns, userTurns: digest.userTurns || 0, chars: digest.chars || 0, omittedTurns: digest.omittedTurns || 0, budget: digest.budget || null, degraded: digest.degraded === true, reason: digest.reason || null }
      publishRun(run, { type: 'history', history: run.history })
    }
    // ── 身份层（唯一入口）：本次运行属于哪个会话 / 工作目录 / 下游形态，只在这里解析一次 ──
    // 解析不到就**不猜**：不派工具、不注入观察者、形态回落 chat —— 退化成"纯需求重述"，绝不产出假事实。
    const rc = resolveRunContext(ctx, run.sessionId)
    run.context = { sessionId: rc.sessionId, cwd: rc.cwd, preset: rc.preset, matched: rc.matched, reason: rc.reason, sessionsSeen: rc.sessionsSeen }
    run.strategy = strategyNow()
    // 观察者上下文（SPEC W1b · 唯一上下文注入路径）：走会话投影 derived，以旁观者视角注入 system。
    // 范围只由 UI 决定（回合 0–10 / 全文 关·开）；**只有确认是这个会话**时才注入，拿不到就留空并记原因。
    const observerBlock = rc.matched
      ? renderObserverBlock(ctx, { mode: run.historyMode === 'off' ? 'off' : (run.historyMode === 'full' ? 'full' : 'turns'), turns: run.turns, sessionId: rc.sessionId })
      : ''
    // 诊断解析：第 2 行形如「（读取范围：X；本段：Y）」——X/Y 内部可能含全角括号，按分隔符取值
    const obsLine = (observerBlock.split('\n')[1] || '')
    const obsDetail = (() => { const a = obsLine.indexOf('本段：'); return a < 0 ? null : obsLine.slice(a + 3).replace(/）\s*$/, '') })()
    const obsRange = (() => { const a = obsLine.indexOf('读取范围：'); if (a < 0) return null; const rest = obsLine.slice(a + 5); const b = rest.indexOf('；本段：'); return b >= 0 ? rest.slice(0, b) : rest.replace(/）\s*$/, '') })()
    run.observer = {
      mode: run.historyMode, chars: observerBlock.length,
      rows: (observerBlock.match(/^【(用户|工作 AI)】/gm) || []).length,
      range: obsRange, detail: obsDetail, stage: obsDetail,
      reason: rc.matched ? (observerBlock ? null : (run.historyMode === 'off' ? 'history-off' : (run.historyMode === 'turns' && !(run.turns > 0) ? 'turns-0' : 'no-context-available'))) : 'no-session:' + rc.reason,
    }
    publishRun(run, { type: 'observer', observer: run.observer })
    const userMsg = relayMessage(run.request, run.direction || null, run.prevText || null, null)
    // 只读查证：高级/极端档且开关打开、**且身份层确认了本会话的工作目录**时才派工具（根目录取错会制造假事实）
    // run.readToolsOverride / run.toolRootOverride 是**显式覆盖**（测试钩子，与 forceError 同类，必须显式传入）：
    // 试题台要拿一个临时目录当"项目"，而那个目录不属于任何会话——不显式指定就永远测不到"读仓库"这条能力。
    // 注意：**显式传入 ≠ 猜**——猜是"不知道就回落到第一个会话"，这里是外部明确给的根，且会写进 /runs 留痕。
    const tierWantsTools = run.tier === 'advanced' || run.tier === 'extreme'
    const readToolsWanted = (run.readToolsOverride === undefined || run.readToolsOverride === null) ? readToolsForCall() : run.readToolsOverride === true
    const rootOverride = typeof run.toolRootOverride === 'string' && run.toolRootOverride ? run.toolRootOverride : null
    const toolRoot = rootOverride || rc.cwd || null
    const useTools = tierWantsTools && readToolsWanted && Boolean(toolRoot)
    run.readTools = useTools
    run.toolRoot = toolRoot
    run.toolRootSource = useTools ? (rootOverride ? 'hook' : 'session') : null
    run.toolCalls = 0
    // 下游消费形态（结构参数）：默认 PTC（本插件为 PTC 优化）；'chat'/'auto' 由状态决定
    const delivery = deliveryForRun(rc)
    run.delivery = { mode: delivery.mode, source: delivery.source }
    const sysForRun = buildSystem(run.tier, { historyMode: run.historyMode, observerBlock, delivery: delivery.mode })
    let res
    if (useTools) {
      // 只读查证：必须走**完整工具循环**（模型请求工具 → 宿主执行 → 回填结果 → 继续），
      // 单次 streamWithTools 只提交工具请求、不产出结论（实测：产出为空）。
      // 只读查证：根目录用**身份层解析出来的本会话 cwd**（此前这里取的是"第一个会话"的目录，
      // 实测读到别的目录并把"这里没有工程文件"当成已核实事实发给下游）
      // 只读查证：根目录 = 上面统一算好的 toolRoot（会话 cwd，或**显式**测试钩子给的目录）
      const root = toolRoot
      // ⚠️ 根因修复：relayMessage() 返回的是**消息数组**（非工具路径当 messages 用），
      // 而 runToolLoop 的 userText 要**字符串**——直接把数组塞进去会变成 content[].text = 对象，
      // provider 于是报 `messages[0].content: invalid type: sequence, expected a string`（实测定位）。
      const userTextForLoop = Array.isArray(userMsg)
        ? userMsg.map((m) => (Array.isArray(m.content) ? m.content.map((b) => (b && b.text) || '').join('') : String((m && m.content) || ''))).join('\n\n')
        : String(userMsg || '')
      const looped = run.forceToolError
        // 调试钩子：只让**工具链**失败（模型本身可用），据此复核"失败 → 降级为无工具运行 → 结果非空"
        ? { error: 'forced-tool-error (debug)', output: '', reasoning: '', trace: [], rounds: 0, debug: { forced: true, reason: 'debug hook' } }
        : await runToolLoop(ctx, {
            // 轮数 3 → 5：实测"先侦察（列目录 + 读约定文档）再定位目标"至少要 2–3 轮，
            // 而 3 轮时模型把整轮花在 glob 上，三次运行都只列到约定文件、一次都没 read。
            root, maxRounds: 5, userText: userTextForLoop, system: sysForRun, selection: selForRun,
            // 透传：思考 / 用量 / **正文**都按流式转发（"产出"栏据此实时显示）；换轮的 text-reset 也走这里
            onDelta: (type, text) => { if (type === 'reasoning-delta' || type === 'usage' || type === 'text-delta' || type === 'text-reset' || type === 'tool-trace') publishRun(run, { type, text }) },
          })
      run.toolLoopDebug = looped.debug || null
      res = {
        error: looped.error || null,
        text: looped.output || '',
        reasoning: looped.reasoning || '',
        usage: null,
        calls: (looped.trace || []).map((t) => ({ name: t.tool })),
        trace: looped.trace || [],
      }
      if (res.text) {
        // 最后一轮的正文已经在循环里**流式**发出去了（streamedText=true）→ 这里不再重复发一遍
        if (!looped.streamedText) publishRun(run, { type: 'text-delta', text: res.text })
      } else {
        // 降级保护：工具循环没拿到产出（报错/空）时，回落到正常路径，绝不给用户空结果
        run.toolLoopError = String(looped.error || 'empty-output')
        run.toolLoopRounds = looped.rounds === undefined ? null : looped.rounds
        run.toolLoopTrace = (looped.trace || []).map((t) => ({ round: t.round, tool: t.tool, ok: t.ok, ms: t.ms, lines: t.resultLines })).slice(0, 8)
        res = await streamWithTools(
          llm, selForRun, sysForRun, userMsg, undefined, spec.temperature, OUTPUT_BUDGET_MS, run.abort.signal,
          (type, text) => publishRun(run, { type, text }),
        )
      }
    } else {
      res = await streamWithTools(
        llm, selForRun, sysForRun, userMsg, undefined, spec.temperature, OUTPUT_BUDGET_MS, run.abort.signal,
        (type, text) => publishRun(run, { type, text }),
      )
    }
    run.toolCalls = Array.isArray(res.calls) ? res.calls.length : 0
    run.toolNames = Array.isArray(res.calls) ? res.calls.map((c) => c.name).slice(0, 8) : []
    // 产出收件人闸门（收件人层·强制）：模型若写出"把下面这段整条发给工作 AI"这类转交语/包装，
    // 在**唯一产出出口**上剥掉——流里的 delta 只是预览，定稿以这里为准（done.text 覆盖预览）。
    const addressee = enforceAddressee(run.text)
    run.addressee = { triggered: addressee.triggered, action: addressee.action, before: addressee.before, after: addressee.after, head: addressee.head, stripped: addressee.text !== run.text }
    if (addressee.text !== run.text) run.text = addressee.text
    // 膨胀闸门（F6 修订）：**只留痕、不裁剪**——分两栏记（自产 / 带出处的搬运），
    // 越界原因也写清楚；裁剪要靠契约，不能靠宿主动刀（动刀会制造半截命令，这是踩过的坑）。
    run.lengthGate = evaluateLengthGate(run.tier, String(run.request || '').length, run.text)
    // ask 段审计（同样只留痕）：产物里写了几条要问用户的，超预算就记下来
    run.askGate = evaluateAskGate(run.tier, run.text)
    if (run.abort.signal.aborted) publishRun(run, { type: 'aborted' })
    else if (res.error) publishRun(run, { type: 'error', message: res.error })
    else publishRun(run, { type: 'done', ms: Date.now() - run.startedAt, firstDeltaMs: run.firstDeltaMs, usage: run.usage || (res && res.usage) || null, text: run.text })
  } catch (error) {
    publishRun(run, { type: 'error', message: String(error) })
  } finally {
    closeRunSubs(run)
  }
}

