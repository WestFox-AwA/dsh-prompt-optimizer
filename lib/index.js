/**
 * **纯函数**：把一次探测采样判成结论（可单测；不含 IO）。
 * 判据刻意保守——只认"必然坏"的信号，避免把"页面本来就暗/本来就没画布"误判成失败。
 */
function gateVerdict(sample) {
  const s = sample || {}
  if (s.opened === false) return { verdict: 'cannot-open', reason: shortReason(s.reason || '浏览器没能打开页面', 160) }
  if (Array.isArray(s.pageErrors) && s.pageErrors.length) return { verdict: 'page-error', reason: shortReason(s.pageErrors[0], 200) }
  const overlay = String(s.overlay || '').trim()
  if (overlay && /失败|错误|无法|异常|超时|不支持|丢失/.test(overlay)) return { verdict: 'fatal-overlay', reason: shortReason(overlay, 200) }
  if (s.canvas) {
    if (!(s.canvasW > 8) || !(s.canvasH > 8)) return { verdict: 'blank-canvas-0', reason: `画布后备缓冲 ${s.canvasW}×${s.canvasH}（CSS 尺寸正常也不会显示任何东西）` }
    const px = s.pixels || null
    if (px && typeof px.mean === 'number' && typeof px.max === 'number' && px.mean < 2 && px.max < 8) {
      return { verdict: 'blank-canvas', reason: `画布中心区域全黑（mean=${px.mean}, max=${px.max}，采样 ${px.w}×${px.h}）` }
    }
  }
  return { verdict: 'ok', reason: '' }
}

