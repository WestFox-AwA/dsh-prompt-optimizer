/**
 * 下游形态（**默认 PTC**，老板口径）：本插件针对 PTC 执行体优化，所以"没设置"就是 ptc，而不是"猜会话"。
 *   state.delivery 缺失（含旧数据的 null / 坏值）→ 插件默认 `DELIVERY_DEFAULT` = 'ptc'（source=default-ptc）
 *   state.delivery = 'ptc' / 'chat' → 用户显式选择（source=manual-ptc / manual-chat）
 *   state.delivery = 'auto' → 才按会话 preset 判定（source=agentPreset:*，解析不到会话 → auto-no-session->ptc）
 * 与身份层解耦：形态是**表达方式**，不依赖是否读到了项目；解析不到会话只影响"派不派工具 / 注不注入观察者"。
 */
function deliveryForRun(runContext) {
  let sel = null
  try { sel = normalizeDelivery(loadPluginState().delivery) } catch { /* 读不到就当没设置 */ }
  if (sel === 'ptc') return { mode: 'ptc', source: 'manual-ptc' }
  if (sel === 'chat') return { mode: 'chat', source: 'manual-chat' }
  // 没显式选过（含旧数据里的 null / 坏值）＝插件默认：**PTC**（本插件就是为 PTC 执行体优化的）
  if (sel !== 'auto') return { mode: DELIVERY_DEFAULT, source: 'default-ptc' }
  // 'auto'：按身份层给的 preset 判定；连会话都解析不到时回落插件默认（PTC）
  const rc = runContext || null
  if (!rc || !rc.matched) return { mode: 'ptc', source: 'auto-no-session->ptc' }
  const preset = rc.preset
  if (typeof preset === 'string' && /(^|[-_])ptc([-_]|$)/i.test(preset)) return { mode: 'ptc', source: 'agentPreset:' + preset }
  return { mode: 'chat', source: 'agentPreset:' + (preset || 'none') }
}

